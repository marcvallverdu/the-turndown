    'public.rollback_failed_content_verification(text,text,uuid,text)'::regprocedure::oid,
    'public.record_content_restoration_verification(text,text,uuid,jsonb)'::regprocedure::oid
  ] LOOP
    EXECUTE format('ALTER FUNCTION %s OWNER TO %I',oid_value::regprocedure,current_user);
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC',oid_value::regprocedure);
    FOR role_name IN SELECT r.rolname FROM pg_catalog.pg_proc p CROSS JOIN LATERAL pg_catalog.aclexplode(coalesce(p.proacl,pg_catalog.acldefault('f',p.proowner))) a JOIN pg_catalog.pg_roles r ON r.oid=a.grantee WHERE p.oid=oid_value AND a.privilege_type='EXECUTE' AND r.rolname NOT IN (current_user,'turndown_content_publisher')
    LOOP EXECUTE format('REVOKE ALL ON FUNCTION %s FROM %I',oid_value::regprocedure,role_name); END LOOP;
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO turndown_content_publisher',oid_value::regprocedure);
  END LOOP;
END $$;

