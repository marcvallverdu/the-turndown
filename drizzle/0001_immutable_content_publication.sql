CREATE OR REPLACE FUNCTION public.enforce_content_item_identity() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  IF NEW.id IS DISTINCT FROM OLD.id OR NEW.content_type IS DISTINCT FROM OLD.content_type OR NEW.slug IS DISTINCT FROM OLD.slug OR NEW.legacy_id IS DISTINCT FROM OLD.legacy_id OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'content item identity is immutable' USING ERRCODE='55000';
  END IF;
  RETURN NEW;
END $$;
