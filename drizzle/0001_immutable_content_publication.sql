CREATE OR REPLACE FUNCTION public.publish_content_version(p_type text,p_slug text,p_version_id uuid,p_checksum text,p_payload jsonb,p_evidence jsonb,p_media jsonb,p_actor text,p_run_id text,p_validation jsonb)
RETURNS TABLE(changed boolean,item_id uuid,content_type text,previous_version_id uuid,previous_published boolean,version_id uuid,checksum text,activation_event_id uuid)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE i public.content_items%ROWTYPE; v public.content_versions%ROWTYPE; proof text; event_id uuid:=gen_random_uuid(); predecessor jsonb; legacy jsonb; new_snapshot jsonb; existed boolean; changed_value boolean; legacy_id text;
BEGIN
  IF p_type NOT IN ('hotel','brand','destination','article') OR p_slug!~'^[a-z0-9]+(-[a-z0-9]+)*$' OR p_actor='' OR p_actor<>btrim(p_actor) OR length(p_actor)>200 OR p_run_id='' OR p_run_id<>btrim(p_run_id) OR length(p_run_id)>200 THEN RAISE EXCEPTION 'invalid publication identity or actor' USING ERRCODE='22023'; END IF;
  IF p_validation->>'checksum' IS DISTINCT FROM p_checksum OR p_validation#>>'{preflight,checksum}' IS DISTINCT FROM p_checksum OR p_validation#>>'{preflight,renderer}'<>'the-turndown-marked-gfm-breaks-sanitized-v1' THEN RAISE EXCEPTION 'validation binding mismatch' USING ERRCODE='22023'; END IF;
  SELECT encode(hmac(decode(public.content_validation_challenge(p_type,p_slug,p_checksum,p_payload,p_evidence,p_media,p_validation),'hex'),k.secret,'sha256'),'hex') INTO STRICT proof FROM public.content_validation_keys k WHERE singleton;
  IF p_validation->>'validatorProof' IS DISTINCT FROM proof THEN RAISE EXCEPTION 'invalid validator proof' USING ERRCODE='42501'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('turndown:content:'||p_type||':'||p_slug,0));
  SELECT x.* INTO i FROM public.content_items x WHERE x.content_type=p_type AND x.slug=p_slug FOR UPDATE; existed:=FOUND;
  IF NOT existed THEN
    legacy_id:=public.content_uuid_from_hex(encode(digest(convert_to(p_type||':'||p_slug,'UTF8'),'sha256'),'hex'))::text;
    INSERT INTO public.content_items(id,content_type,slug,legacy_id,created_at,updated_at) VALUES(legacy_id::uuid,p_type,p_slug,legacy_id,(p_payload->>'createdAt')::timestamptz,(p_payload->>'updatedAt')::timestamptz) RETURNING * INTO i;
    new_snapshot:=public.content_snapshot_from_payload(p_type,legacy_id,p_slug,p_payload,0); PERFORM public.content_restore_legacy(p_type,new_snapshot);
  END IF;
  IF public.content_has_pending(i.id) THEN RAISE EXCEPTION 'pending activation must be recovered before publication' USING ERRCODE='40001'; END IF;
  legacy:=public.content_legacy_snapshot(p_type,p_slug);
  predecessor:=jsonb_build_object('itemExisted',existed,'legacyExisted',legacy IS NOT NULL,'legacyRow',legacy,'activeVersionId',i.active_version_id,'published',coalesce((legacy->>'published')::integer,0)=1,'createdAsDraft',NOT existed);
  SELECT x.* INTO v FROM public.content_versions x WHERE x.item_id=i.id AND x.payload_checksum=p_checksum;
  new_snapshot:=public.content_snapshot_from_payload(p_type,i.legacy_id,p_slug,p_payload,1);
  IF FOUND THEN
    IF v.id<>p_version_id OR v.payload IS DISTINCT FROM p_payload OR v.source_evidence IS DISTINCT FROM p_evidence OR v.media_manifest IS DISTINCT FROM p_media OR v.validation_result IS DISTINCT FROM p_validation OR v.legacy_snapshot IS DISTINCT FROM new_snapshot THEN RAISE EXCEPTION 'altered immutable version reuse denied' USING ERRCODE='40001'; END IF;
  ELSE
    IF EXISTS(SELECT 1 FROM public.content_versions x WHERE x.id=p_version_id) THEN RAISE EXCEPTION 'deterministic version ID collision' USING ERRCODE='23505'; END IF;
    INSERT INTO public.content_versions(id,item_id,content_type,schema_version,payload,payload_checksum,source_evidence,media_manifest,legacy_snapshot,created_at,created_by,run_id,validation_result)
      VALUES(p_version_id,i.id,p_type,1,p_payload,p_checksum,p_evidence,p_media,new_snapshot,(p_payload->>'createdAt')::timestamptz,p_actor,p_run_id,p_validation) RETURNING * INTO v;
  END IF;
  changed_value:=i.active_version_id IS DISTINCT FROM v.id OR coalesce((legacy->>'published')::integer,0)<>1;
  UPDATE public.content_items SET active_version_id=v.id,updated_at=(p_payload->>'updatedAt')::timestamptz WHERE id=i.id;
  PERFORM public.content_restore_legacy(p_type,v.legacy_snapshot);
  INSERT INTO public.content_publication_events(id,item_id,event_type,previous_version_id,next_version_id,actor,run_id,predecessor_state)
    VALUES(event_id,i.id,CASE WHEN i.active_version_id IS NULL THEN 'published' ELSE 'reactivated' END,i.active_version_id,v.id,p_actor,p_run_id,predecessor);
  RETURN QUERY SELECT changed_value,i.id,p_type,i.active_version_id,coalesce((predecessor->>'published')::boolean,false),v.id,v.payload_checksum,event_id;
END $$;

CREATE OR REPLACE FUNCTION public.activate_content_version(p_type text,p_slug text,p_version_id uuid,p_kind text,p_actor text,p_run_id text)
RETURNS TABLE(changed boolean,item_id uuid,content_type text,previous_version_id uuid,previous_published boolean,version_id uuid,checksum text,activation_event_id uuid)
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE i public.content_items%ROWTYPE; v public.content_versions%ROWTYPE; event_id uuid:=gen_random_uuid(); legacy jsonb; changed_value boolean;
BEGIN
  IF p_kind NOT IN ('reactivate','rollback') OR p_actor='' OR p_actor<>btrim(p_actor) OR p_run_id='' OR p_run_id<>btrim(p_run_id) THEN RAISE EXCEPTION 'invalid activation request' USING ERRCODE='22023'; END IF;
  PERFORM pg_advisory_xact_lock(hashtextextended('turndown:content:'||p_type||':'||p_slug,0));
  SELECT x.* INTO STRICT i FROM public.content_items x WHERE x.content_type=p_type AND x.slug=p_slug FOR UPDATE;
  IF public.content_has_pending(i.id) THEN RAISE EXCEPTION 'pending activation must be recovered before historical activation' USING ERRCODE='40001'; END IF;
  SELECT x.* INTO STRICT v FROM public.content_versions x WHERE x.id=p_version_id AND x.item_id=i.id AND x.content_type=p_type;
  legacy:=public.content_legacy_snapshot(p_type,p_slug); changed_value:=i.active_version_id IS DISTINCT FROM v.id OR coalesce((legacy->>'published')::integer,0)<>1;
  UPDATE public.content_items SET active_version_id=v.id,updated_at=(v.payload->>'updatedAt')::timestamptz WHERE id=i.id; PERFORM public.content_restore_legacy(p_type,v.legacy_snapshot);
  INSERT INTO public.content_publication_events(id,item_id,event_type,previous_version_id,next_version_id,actor,run_id,predecessor_state)
    VALUES(event_id,i.id,CASE WHEN p_kind='rollback' THEN 'rolled_back' ELSE 'reactivated' END,i.active_version_id,v.id,p_actor,p_run_id,jsonb_build_object('itemExisted',true,'legacyExisted',legacy IS NOT NULL,'legacyRow',legacy,'activeVersionId',i.active_version_id,'published',coalesce((legacy->>'published')::integer,0)=1));
  RETURN QUERY SELECT changed_value,i.id,p_type,i.active_version_id,coalesce((legacy->>'published')::integer,0)=1,v.id,v.payload_checksum,event_id;
END $$;

