      'createdAt',to_jsonb((p_row->>'created_at')::timestamptz),'updatedAt',to_jsonb((p_row->>'updated_at')::timestamptz));
    WHEN 'brand' THEN RETURN jsonb_build_object(
      'name',p_row->'name','tagline',p_row->'tagline','heroImage',p_row->'hero_image','contentMd',p_row->'content_md',
      'hotelCount',coalesce(p_row->'hotel_count','0'::jsonb),'foundedYear',p_row->'founded_year','parentCompany',p_row->'parent_company',
      'bestProperty',p_row->'best_property','website',p_row->'website','createdAt',to_jsonb((p_row->>'created_at')::timestamptz),
      'updatedAt',to_jsonb((p_row->>'updated_at')::timestamptz));
    WHEN 'destination' THEN RETURN jsonb_build_object(
      'name',p_row->'name','country',p_row->'country','region',p_row->'region','heroImage',p_row->'hero_image',
      'introMd',p_row->'intro_md','bestTime',p_row->'best_time','contentMd',p_row->'content_md',
