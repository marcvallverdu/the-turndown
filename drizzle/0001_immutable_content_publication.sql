      'priceTo',p_row->'price_to','currency',p_row->'currency','style',p_row->'style',
      'bestFor',public.content_json_text_array(p_row->>'best_for'),'heroImage',p_row->'hero_image',
      'images',public.content_json_text_array(p_row->>'images'),'website',p_row->'website','bookingUrl',p_row->'booking_url',
      'tagline',p_row->'tagline','reviewIntro',p_row->'review_intro','reviewArrival',p_row->'review_arrival',
