-- Snapshot every predecessor table before any pointer is installed.
WITH legacy AS (
  SELECT 'hotel'::text content_type,id::text legacy_id,slug,coalesce(created_at,now()) created_at,coalesce(updated_at,created_at,now()) updated_at,to_jsonb(h.*) snapshot,coalesce(published,0)=1 published FROM public.hotels h
  UNION ALL SELECT 'brand',id::text,slug,coalesce(created_at,now()),coalesce(updated_at,created_at,now()),to_jsonb(b.*),coalesce(published,0)=1 FROM public.brands b
  UNION ALL SELECT 'destination',id::text,slug,coalesce(created_at,now()),coalesce(updated_at,created_at,now()),to_jsonb(d.*),coalesce(published,0)=1 FROM public.destinations d
  UNION ALL SELECT 'article',id::text,slug,coalesce(created_at,now()),coalesce(updated_at,created_at,now()),to_jsonb(a.*),coalesce(published,0)=1 FROM public.articles a
), prepared AS (
  SELECT *,encode(digest(convert_to(content_type||':'||slug,'UTF8'),'sha256'),'hex') item_hex FROM legacy
)
INSERT INTO public.content_items(id,content_type,slug,legacy_id,created_at,updated_at)
SELECT public.content_uuid_from_hex(item_hex),content_type,slug,legacy_id,created_at,updated_at FROM prepared
ON CONFLICT(content_type,slug) DO NOTHING;

WITH legacy AS (
  SELECT 'hotel'::text content_type,id::text legacy_id,slug,coalesce(created_at,now()) created_at,to_jsonb(h.*) snapshot FROM public.hotels h
  UNION ALL SELECT 'brand',id::text,slug,coalesce(created_at,now()),to_jsonb(b.*) FROM public.brands b
  UNION ALL SELECT 'destination',id::text,slug,coalesce(created_at,now()),to_jsonb(d.*) FROM public.destinations d
  UNION ALL SELECT 'article',id::text,slug,coalesce(created_at,now()),to_jsonb(a.*) FROM public.articles a
), canonical AS (
  SELECT l.*,i.id item_id,public.content_payload_from_legacy(l.content_type,l.snapshot) payload,
    jsonb_build_object('schemaVersion',1,'contentType',l.content_type,'slug',l.slug,'payload',public.content_payload_from_legacy(l.content_type,l.snapshot)) canonical
  FROM legacy l JOIN public.content_items i ON i.content_type=l.content_type AND i.slug=l.slug
  WHERE NOT EXISTS(SELECT 1 FROM public.content_versions v WHERE v.item_id=i.id)
), hashed AS (
  SELECT *,encode(digest(convert_to(canonical::text,'UTF8'),'sha256'),'hex') checksum_hex FROM canonical
)
INSERT INTO public.content_versions(id,item_id,content_type,schema_version,payload,payload_checksum,source_evidence,media_manifest,legacy_snapshot,created_at,created_by,run_id,validation_result)
SELECT public.content_uuid_from_hex(checksum_hex),item_id,content_type,1,payload,'sha256:'||checksum_hex,
  jsonb_build_object(
    'bootstrap',true,
    'source','exact-legacy-row',
    'normalizedLegacyArrayEncoding',CASE WHEN content_type='hotel' THEN jsonb_build_object(
      'bestForPostgresLiteral',coalesce(ltrim(snapshot->>'best_for') LIKE '{%',false),
      'imagesPostgresLiteral',coalesce(ltrim(snapshot->>'images') LIKE '{%',false),
      'bestForUnquotedBracketList',coalesce(ltrim(snapshot->>'best_for') LIKE '[%' AND ltrim(snapshot->>'best_for') NOT LIKE '["%',false),
      'imagesUnquotedBracketList',coalesce(ltrim(snapshot->>'images') LIKE '[%' AND ltrim(snapshot->>'images') NOT LIKE '["%',false)
    ) ELSE '{}'::jsonb END
  ), '[]'::jsonb,snapshot,created_at,
  'migration:0001_content_publication','migration:0001_content_publication',jsonb_build_object('valid',true,'mode','audited-legacy-bootstrap')
FROM hashed ON CONFLICT(item_id,payload_checksum) DO NOTHING;

UPDATE public.content_items i SET active_version_id=v.id
FROM public.content_versions v
WHERE v.item_id=i.id AND i.active_version_id IS NULL
AND CASE i.content_type
  WHEN 'hotel' THEN EXISTS(SELECT 1 FROM public.hotels x WHERE x.slug=i.slug AND coalesce(x.published,0)=1)
  WHEN 'brand' THEN EXISTS(SELECT 1 FROM public.brands x WHERE x.slug=i.slug AND coalesce(x.published,0)=1)
  WHEN 'destination' THEN EXISTS(SELECT 1 FROM public.destinations x WHERE x.slug=i.slug AND coalesce(x.published,0)=1)
  WHEN 'article' THEN EXISTS(SELECT 1 FROM public.articles x WHERE x.slug=i.slug AND coalesce(x.published,0)=1)
END;

INSERT INTO public.content_publication_events(item_id,event_type,previous_version_id,next_version_id,actor,run_id,occurred_at,verification_evidence,predecessor_state)
SELECT i.id,'bootstrap',NULL,i.active_version_id,'migration:0001_content_publication','migration:0001_content_publication',i.updated_at,
  jsonb_build_object('mode','audited-legacy-bootstrap','published',i.active_version_id IS NOT NULL),
  jsonb_build_object('itemExisted',true,'legacyExisted',true,'legacyRow',v.legacy_snapshot,'activeVersionId',i.active_version_id)
FROM public.content_items i JOIN public.content_versions v ON v.item_id=i.id
WHERE v.created_by='migration:0001_content_publication'
AND NOT EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.item_id=i.id AND e.event_type='bootstrap' AND e.run_id='migration:0001_content_publication');

CREATE OR REPLACE FUNCTION public.content_is_canonical_https_url(p_value text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE u text;
BEGIN
  IF p_value IS NULL OR length(p_value) NOT BETWEEN 1 AND 2048 OR p_value !~ '^https://[^/?#]+(?:[/?][^#]*)?$' OR position('#' IN p_value)>0 THEN RETURN false; END IF;
  u:=split_part(split_part(substr(p_value,9),'/',1),'?',1);
  RETURN u<>'' AND position('@' IN u)=0 AND lower(u)!~'^(localhost|[^:]+\.localhost)(:[0-9]+)?$'
    AND lower(u)!~'^(127\.|10\.|192\.168\.|169\.254\.|172\.(1[6-9]|2[0-9]|3[01])\.)'
    AND lower(u)!~'^\[(::|::1|fc[0-9a-f:]*|fd[0-9a-f:]*|fe[89ab][0-9a-f:]*)\](:[0-9]+)?$';
END $$;

CREATE OR REPLACE FUNCTION public.content_is_timestamp(p_value text) RETURNS boolean
LANGUAGE plpgsql IMMUTABLE SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
  RETURN p_value ~ '^[0-9]{4}-(0[1-9]|1[0-2])-([0-2][0-9]|3[01])T([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]\.[0-9]{3}Z$'
    AND to_char(p_value::timestamptz AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')=p_value;
EXCEPTION WHEN others THEN RETURN false;
END $$;

CREATE OR REPLACE FUNCTION public.enforce_content_version_integrity() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE item_slug text; canonical jsonb; hex text; expected uuid; expected_keys text[]; referenced text[]; manifest_urls text[]; super boolean;
BEGIN
  SELECT slug INTO STRICT item_slug FROM public.content_items WHERE id=NEW.item_id AND content_type=NEW.content_type;
  canonical:=jsonb_build_object('schemaVersion',NEW.schema_version,'contentType',NEW.content_type,'slug',item_slug,'payload',NEW.payload);
  hex:=encode(digest(convert_to(canonical::text,'UTF8'),'sha256'),'hex'); expected:=public.content_uuid_from_hex(hex);
  IF NEW.payload_checksum<>'sha256:'||hex OR NEW.id<>expected THEN RAISE EXCEPTION 'checksum or deterministic version ID mismatch' USING ERRCODE='23514'; END IF;
  IF NEW.validation_result->>'mode'='audited-legacy-bootstrap' THEN
    SELECT rolsuper INTO super FROM pg_catalog.pg_roles WHERE rolname=current_user;
    IF NOT coalesce(super,false) OR NEW.created_by<>'migration:0001_content_publication' OR NEW.run_id<>'migration:0001_content_publication' THEN RAISE EXCEPTION 'legacy bootstrap is migration-only' USING ERRCODE='42501'; END IF;
    RETURN NEW;
  END IF;
  expected_keys:=CASE NEW.content_type
    WHEN 'hotel' THEN ARRAY['name','brand','brandSlug','location','country','countrySlug','region','regionSlug','latitude','longitude','priceRange','priceFrom','priceTo','currency','style','bestFor','heroImage','images','website','bookingUrl','tagline','reviewIntro','reviewArrival','reviewRoom','reviewService','reviewFood','reviewDetails','reviewVerdict','verdictBestFor','verdictSkipIf','verdictStandout','ratingOverall','ratingRoom','ratingService','ratingFood','ratingValue','ratingLocation','featured','createdAt','updatedAt']
    WHEN 'brand' THEN ARRAY['name','tagline','heroImage','contentMd','hotelCount','foundedYear','parentCompany','bestProperty','website','createdAt','updatedAt']
    WHEN 'destination' THEN ARRAY['name','country','region','heroImage','introMd','bestTime','contentMd','createdAt','updatedAt']
    ELSE ARRAY['title','subtitle','category','heroImage','contentMd','hotelsMentioned','featured','createdAt','updatedAt'] END;
  IF jsonb_typeof(NEW.payload)<>'object' OR (SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(NEW.payload) k) IS DISTINCT FROM (SELECT array_agg(k ORDER BY k) FROM unnest(expected_keys) k)
     OR (NEW.content_type='article' AND NEW.payload->>'category' NOT IN ('the-details','versus','new-openings'))
     OR NOT public.content_is_timestamp(NEW.payload->>'createdAt') OR NOT public.content_is_timestamp(NEW.payload->>'updatedAt')
     OR coalesce(NEW.payload->>'name',NEW.payload->>'title','')='' THEN RAISE EXCEPTION 'malformed or route-incompatible payload' USING ERRCODE='23514'; END IF;
  IF jsonb_typeof(NEW.source_evidence)<>'object'
     OR (SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(NEW.source_evidence) k)<>ARRAY['claims','hardGates','revisionCount','sources']
     OR NEW.source_evidence->'hardGates'<>'{"truth":true,"userValue":true,"informationGain":true,"internalLinks":true,"editorialSameness":true}'::jsonb
     OR jsonb_typeof(NEW.source_evidence->'sources')<>'array' OR jsonb_array_length(NEW.source_evidence->'sources') NOT BETWEEN 1 AND 100
     OR jsonb_typeof(NEW.source_evidence->'claims')<>'array' OR jsonb_array_length(NEW.source_evidence->'claims') NOT BETWEEN 1 AND 200
     OR (NEW.source_evidence->>'revisionCount') !~ '^[0-2]$' THEN RAISE EXCEPTION 'incomplete source evidence' USING ERRCODE='23514'; END IF;
  IF EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.source_evidence->'sources') s WHERE
      (SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(s) k)<>ARRAY['checkedAt','id','url'] OR NOT public.content_is_canonical_https_url(s->>'url') OR NOT public.content_is_timestamp(s->>'checkedAt') OR coalesce(s->>'id','')='')
     OR (SELECT count(*) FROM jsonb_array_elements(NEW.source_evidence->'sources'))<>(SELECT count(DISTINCT s->>'id') FROM jsonb_array_elements(NEW.source_evidence->'sources') s)
     OR EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.source_evidence->'claims') c WHERE
       (SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(c) k)<>ARRAY['claim','sourceIds']
       OR jsonb_typeof(c->'sourceIds')<>'array' OR jsonb_array_length(c->'sourceIds')<1 OR coalesce(c->>'claim','')=''
       OR (SELECT count(*) FROM jsonb_array_elements_text(c->'sourceIds'))<>(SELECT count(DISTINCT sid) FROM jsonb_array_elements_text(c->'sourceIds') sid)
       OR EXISTS(SELECT 1 FROM jsonb_array_elements_text(c->'sourceIds') sid WHERE NOT EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.source_evidence->'sources') s WHERE s->>'id'=sid)))
  THEN RAISE EXCEPTION 'malformed claims or sources' USING ERRCODE='23514'; END IF;
  IF NEW.validation_result->>'valid'<>'true' OR NEW.validation_result->>'validator'<>'turndown-content-envelope-v1'
     OR NEW.validation_result->>'checksum' IS DISTINCT FROM NEW.payload_checksum
     OR NEW.validation_result#>>'{preflight,checksum}' IS DISTINCT FROM NEW.payload_checksum
     OR NEW.validation_result#>>'{preflight,renderer}'<>'the-turndown-marked-gfm-breaks-sanitized-v1' THEN RAISE EXCEPTION 'validation does not bind renderer and checksum' USING ERRCODE='23514'; END IF;
  IF jsonb_typeof(NEW.media_manifest)<>'array' OR jsonb_array_length(NEW.media_manifest)>100
     OR EXISTS(SELECT 1 FROM jsonb_array_elements(NEW.media_manifest) m WHERE
       (SELECT array_agg(k ORDER BY k) FROM jsonb_object_keys(m) k)<>ARRAY['byteLength','checksum','contentType','height','provenance','retrievedAt','url','width']
       OR NOT public.content_is_canonical_https_url(m->>'url') OR m->>'checksum' !~ '^sha256:[0-9a-f]{64}$'
       OR m->>'contentType' NOT IN ('image/png','image/jpeg','image/webp') OR (m->>'width')::integer NOT BETWEEN 1 AND 20000
       OR (m->>'height')::integer NOT BETWEEN 1 AND 20000 OR (m->>'byteLength')::integer NOT BETWEEN 1 AND 20000000
       OR NOT public.content_is_timestamp(m->>'retrievedAt')) THEN RAISE EXCEPTION 'malformed media manifest' USING ERRCODE='23514'; END IF;
  referenced:=ARRAY(SELECT x FROM (SELECT NEW.payload->>'heroImage' x UNION ALL SELECT jsonb_array_elements_text(CASE WHEN NEW.content_type='hotel' THEN NEW.payload->'images' ELSE '[]'::jsonb END)) q WHERE x IS NOT NULL);
  manifest_urls:=ARRAY(SELECT m->>'url' FROM jsonb_array_elements(NEW.media_manifest) m);
  IF referenced IS DISTINCT FROM manifest_urls AND (SELECT array_agg(x ORDER BY x) FROM unnest(referenced) x) IS DISTINCT FROM (SELECT array_agg(x ORDER BY x) FROM unnest(manifest_urls) x) THEN
    RAISE EXCEPTION 'media manifest does not exactly bind referenced images' USING ERRCODE='23514'; END IF;
  RETURN NEW;
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN RAISE EXCEPTION 'malformed numeric media or payload field' USING ERRCODE='23514';
END $$;

