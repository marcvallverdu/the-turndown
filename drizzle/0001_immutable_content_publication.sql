    WHEN 'hotel' THEN RETURN jsonb_build_object(
      'name',p_row->'name','brand',p_row->'brand','brandSlug',p_row->'brand_slug','location',p_row->'location',
      'country',p_row->'country','countrySlug',p_row->'country_slug','region',p_row->'region','regionSlug',p_row->'region_slug',
