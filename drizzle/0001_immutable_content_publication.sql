CREATE OR REPLACE FUNCTION public.rollback_failed_content_verification(p_type text,p_slug text,p_activation uuid,p_error text) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE i public.content_items%ROWTYPE; a public.content_publication_events%ROWTYPE; latest uuid; state jsonb; failed uuid; restored uuid;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('turndown:content:'||p_type||':'||p_slug,0));
  SELECT x.* INTO STRICT i FROM public.content_items x WHERE x.content_type=p_type AND x.slug=p_slug FOR UPDATE;
  SELECT e.* INTO STRICT a FROM public.content_publication_events e WHERE e.id=p_activation AND e.item_id=i.id AND e.activation_event_id IS NULL AND e.event_type IN ('published','reactivated','rolled_back');
  SELECT e.id INTO latest FROM public.content_publication_events e WHERE e.item_id=i.id AND e.activation_event_id IS NULL AND e.event_type IN ('published','reactivated','rolled_back') ORDER BY e.event_order DESC LIMIT 1;
  failed:=a.next_version_id; state:=a.predecessor_state;
  IF EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.activation_event_id=p_activation AND e.event_type='rolled_back')
     AND NOT EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.activation_event_id=p_activation AND e.event_type IN ('verified','verification_failed')) THEN RETURN; END IF;
  IF latest IS DISTINCT FROM p_activation OR i.active_version_id IS DISTINCT FROM failed OR EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.activation_event_id=p_activation AND e.event_type IN ('verified','verification_failed')) THEN RAISE EXCEPTION 'stale or already-settled activation rollback denied' USING ERRCODE='40001'; END IF;
  restored:=CASE WHEN state->'activeVersionId'='null'::jsonb THEN NULL ELSE (state->>'activeVersionId')::uuid END;
  UPDATE public.content_items SET active_version_id=restored,updated_at=CASE WHEN state->'legacyRow' IS NULL OR state->'legacyRow'='null'::jsonb THEN updated_at ELSE (state#>>'{legacyRow,updated_at}')::timestamptz END WHERE id=i.id;
  IF coalesce((state->>'legacyExisted')::boolean,false) THEN PERFORM public.content_restore_legacy(p_type,state->'legacyRow'); END IF;
  INSERT INTO public.content_publication_events(item_id,event_type,previous_version_id,next_version_id,actor,run_id,verification_evidence,activation_event_id)
    VALUES(i.id,'rolled_back',failed,restored,'live-verifier','verification-rollback:'||p_activation,jsonb_build_object('reason','live-verification-failed','restoredPublished',coalesce((state->>'published')::boolean,false)),p_activation);
END $$;

CREATE OR REPLACE FUNCTION public.record_content_restoration_verification(p_type text,p_slug text,p_activation uuid,p_evidence jsonb) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE i public.content_items%ROWTYPE; a public.content_publication_events%ROWTYPE; restored uuid;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('turndown:content:'||p_type||':'||p_slug,0));
  SELECT x.* INTO STRICT i FROM public.content_items x WHERE x.content_type=p_type AND x.slug=p_slug FOR UPDATE;
  SELECT e.* INTO STRICT a FROM public.content_publication_events e WHERE e.id=p_activation AND e.item_id=i.id AND e.activation_event_id IS NULL AND e.event_type IN ('published','reactivated','rolled_back');
  restored:=CASE WHEN a.predecessor_state->'activeVersionId'='null'::jsonb THEN NULL ELSE (a.predecessor_state->>'activeVersionId')::uuid END;
  IF i.active_version_id IS DISTINCT FROM restored
     OR NOT EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.activation_event_id=p_activation AND e.event_type='rolled_back')
     OR EXISTS(SELECT 1 FROM public.content_publication_events e WHERE e.activation_event_id=p_activation AND e.event_type IN ('verified','verification_failed')) THEN
    RAISE EXCEPTION 'restoration verification is stale or mismatched' USING ERRCODE='40001';
  END IF;
  INSERT INTO public.content_publication_events(item_id,event_type,previous_version_id,next_version_id,actor,run_id,verification_evidence,activation_event_id)
    VALUES(i.id,'verification_failed',a.next_version_id,restored,'live-verifier','restoration:'||p_activation,p_evidence||jsonb_build_object('activationEventId',p_activation,'failedVersionId',a.next_version_id,'restoredVersionId',restored),p_activation);
END $$;

