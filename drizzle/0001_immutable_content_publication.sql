CREATE OR REPLACE FUNCTION public.record_content_verification(p_type text,p_slug text,p_activation uuid,p_version uuid,p_checksum text,p_evidence jsonb) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE i public.content_items%ROWTYPE; a public.content_publication_events%ROWTYPE; latest uuid; checksum_value text;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('turndown:content:'||p_type||':'||p_slug,0));
  SELECT x.* INTO STRICT i FROM public.content_items x WHERE x.content_type=p_type AND x.slug=p_slug FOR UPDATE;
  SELECT e.* INTO STRICT a FROM public.content_publication_events e WHERE e.id=p_activation AND e.item_id=i.id AND e.activation_event_id IS NULL AND e.event_type IN ('published','reactivated','rolled_back');
  SELECT e.id INTO latest FROM public.content_publication_events e WHERE e.item_id=i.id AND e.activation_event_id IS NULL AND e.event_type IN ('published','reactivated','rolled_back') ORDER BY e.event_order DESC LIMIT 1;
  SELECT v.payload_checksum INTO STRICT checksum_value FROM public.content_versions v WHERE v.id=p_version AND v.item_id=i.id;
  IF latest IS DISTINCT FROM p_activation OR a.next_version_id IS DISTINCT FROM p_version OR i.active_version_id IS DISTINCT FROM p_version OR checksum_value IS DISTINCT FROM p_checksum THEN RAISE EXCEPTION 'stale or mismatched verification settlement denied' USING ERRCODE='40001'; END IF;
