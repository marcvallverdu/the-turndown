CREATE OR REPLACE FUNCTION public.content_uuid_from_hex(p_hex text) RETURNS uuid
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog, public, pg_temp AS $$
  SELECT (substr(p_hex,1,8)||'-'||substr(p_hex,9,4)||'-5'||substr(p_hex,14,3)||'-'||
    CASE WHEN substr(p_hex,17,1) IN ('0','4','8','c') THEN '8'
         WHEN substr(p_hex,17,1) IN ('1','5','9','d') THEN '9'
         WHEN substr(p_hex,17,1) IN ('2','6','a','e') THEN 'a' ELSE 'b' END ||
    substr(p_hex,18,3)||'-'||substr(p_hex,21,12))::uuid
$$;

CREATE OR REPLACE FUNCTION public.content_json_text_array(p_value text) RETURNS jsonb
LANGUAGE plpgsql IMMUTABLE SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE parsed jsonb;
BEGIN
  IF p_value IS NULL OR p_value='' THEN RETURN '[]'::jsonb; END IF;
  IF left(ltrim(p_value),1)='[' THEN
    BEGIN
      parsed:=p_value::jsonb;
      IF jsonb_typeof(parsed)<>'array' THEN RAISE EXCEPTION 'legacy JSON value is not an array'; END IF;
      RETURN parsed;
    EXCEPTION WHEN invalid_text_representation THEN
      IF right(rtrim(p_value),1)<>']' THEN RAISE EXCEPTION 'unterminated legacy bracket array'; END IF;
      SELECT coalesce(jsonb_agg(to_jsonb(btrim(entry, ' "')) ORDER BY ordinal),'[]'::jsonb)
        INTO parsed
      FROM unnest(string_to_array(substr(btrim(p_value),2,length(btrim(p_value))-2),',')) WITH ORDINALITY AS values(entry,ordinal)
      WHERE btrim(entry, ' "')<>'';
      RETURN parsed;
    END;
  END IF;
  IF left(ltrim(p_value),1)='{' THEN RETURN to_jsonb(p_value::text[]); END IF;
  RAISE EXCEPTION 'legacy array value is neither a JSON array nor a PostgreSQL text array';
END $$;

CREATE TABLE IF NOT EXISTS public.content_items (
  id uuid PRIMARY KEY,
  content_type text NOT NULL CHECK (content_type IN ('hotel','brand','destination','article')),
  slug text NOT NULL CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  legacy_id text NOT NULL,
  active_version_id uuid,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  UNIQUE(content_type,slug),
  UNIQUE(content_type,legacy_id),
  UNIQUE(id,content_type)
);

CREATE TABLE IF NOT EXISTS public.content_versions (
  id uuid PRIMARY KEY,
  item_id uuid NOT NULL REFERENCES public.content_items(id) ON DELETE RESTRICT,
  content_type text NOT NULL CHECK (content_type IN ('hotel','brand','destination','article')),
  schema_version integer NOT NULL CHECK (schema_version=1),
  payload jsonb NOT NULL,
  payload_checksum text NOT NULL CHECK (payload_checksum ~ '^sha256:[0-9a-f]{64}$'),
  source_evidence jsonb NOT NULL,
  media_manifest jsonb NOT NULL,
  legacy_snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by text NOT NULL,
  run_id text NOT NULL,
  validation_result jsonb NOT NULL,
  UNIQUE(id,item_id),
  UNIQUE(item_id,payload_checksum),
  FOREIGN KEY(item_id,content_type) REFERENCES public.content_items(id,content_type) DEFERRABLE INITIALLY IMMEDIATE
);

DO $$ BEGIN
  ALTER TABLE public.content_items ADD CONSTRAINT content_items_active_version_owner_fk
    FOREIGN KEY(active_version_id,id) REFERENCES public.content_versions(id,item_id) DEFERRABLE INITIALLY IMMEDIATE;
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS public.content_publication_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  event_order bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  item_id uuid NOT NULL REFERENCES public.content_items(id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN ('bootstrap','published','reactivated','rolled_back','verified','verification_failed')),
  previous_version_id uuid,
  next_version_id uuid,
  actor text NOT NULL,
  run_id text NOT NULL,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  verification_evidence jsonb,
  activation_event_id uuid REFERENCES public.content_publication_events(id) DEFERRABLE INITIALLY IMMEDIATE,
  predecessor_state jsonb,
  FOREIGN KEY(previous_version_id,item_id) REFERENCES public.content_versions(id,item_id) DEFERRABLE INITIALLY IMMEDIATE,
  FOREIGN KEY(next_version_id,item_id) REFERENCES public.content_versions(id,item_id) DEFERRABLE INITIALLY IMMEDIATE
);
ALTER TABLE public.content_publication_events ADD COLUMN IF NOT EXISTS event_order bigint GENERATED BY DEFAULT AS IDENTITY;
CREATE UNIQUE INDEX IF NOT EXISTS content_publication_events_order_unique ON public.content_publication_events(event_order);
CREATE UNIQUE INDEX IF NOT EXISTS content_activation_terminal_outcome_unique
  ON public.content_publication_events(activation_event_id)
  WHERE activation_event_id IS NOT NULL AND event_type IN ('verified','verification_failed');
CREATE INDEX IF NOT EXISTS content_versions_item_created_idx ON public.content_versions(item_id,created_at DESC);
CREATE INDEX IF NOT EXISTS content_events_item_order_idx ON public.content_publication_events(item_id,event_order DESC);

